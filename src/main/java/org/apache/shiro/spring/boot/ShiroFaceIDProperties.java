package org.apache.shiro.spring.boot;

import org.springframework.boot.context.properties.ConfigurationProperties;

@ConfigurationProperties(ShiroFaceIDProperties.PREFIX)
/**
 * Configuration properties.
 * <p>Binds to the application property prefix and provides
 * customizable settings.</p>
 *
 * @author <a href="https://github.com/loong10k">Loong Wan</a>
 * @since 1.0.0
 */
public class ShiroFaceIDProperties {

	/**
	 * Returns the enabled.
	 *
	 * @return the enabled
	 */
	public static final String PREFIX = "shiro.kisso";
	
	/**
	 * Enable Shiro Kisso.
	 */
	private boolean enabled = false;
	
	/**
	 * Returns the enabled.
	 *
	 * @return the enabled
	 */
	public boolean isEnabled() {
		return enabled;
	}

	/**
	 * Sets the enabled.
	 *
	 * @param enabled the enabled
	 */
	public void setEnabled(boolean enabled) {
		this.enabled = enabled;
	}
	
}

